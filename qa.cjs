const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, headless: true });
  const base = 'http://127.0.0.1:8843/';
  const failures = [];
  for (const width of [320, 375, 720, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 760 } });
    page.on('pageerror', error => failures.push(`${width}: ${error.message}`));
    await page.goto(base, { waitUntil: 'load' });
    assert.equal(await page.locator('header nav a').count(), 6);
    assert.equal(await page.locator('header nav a:visible').count(), 6);
    if (width === 1440) {
      const desktop = await browser.newPage({ viewport: { width, height: 900 } });
      await desktop.goto(base, { waitUntil: 'load' });
      const prompt = await desktop.locator('.scroll-prompt').boundingBox();
      const choice = await desktop.locator('.choice.primary').boundingBox();
      assert.ok(prompt && choice && (prompt.x >= choice.x + choice.width || choice.x >= prompt.x + prompt.width || prompt.y >= choice.y + choice.height || choice.y >= prompt.y + prompt.height), 'desktop reading link overlaps entrance choice');
      await desktop.close();
    }
    if (width === 320 || width === 375) {
      const short = await browser.newPage({ viewport: { width, height: 667 } });
      await short.goto(base, { waitUntil: 'load' });
      const box = await short.locator('.hero-case-link').boundingBox();
      assert.ok(box && box.y + box.height <= 667, `${width}: case link below first short viewport`);
      if (width === 320) await short.screenshot({ path: 'previews/c-drohne-hero-320-20261019.png' });
      await short.close();
    }
    await page.locator('[data-route="voice"]').click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'route-text');
    for (const [variant, expected] of [['stale', '3 Meldungen'], ['missing', 'keine gebundene Erfassungszeit'], ['conflict', 'widersprüchliche aktuelle Aussagen'], ['late', 'frische Zustellung macht das ältere Ereignis nicht aktuell']]) {
      await page.locator('#case-variant').selectOption(variant);
      await page.locator('#case-run').click();
      assert.ok((await page.locator('#case-output').innerText()).includes(expected), `${width}: ${variant}`);
    }
    await page.locator('#case-variant').selectOption('absent');
    await page.locator('#case-run').click();
    assert.match(await page.locator('#case-output').innerText(), /2 Meldungen.*1 deklarierte/);
    assert.match(await page.locator('#case-input-count').innerText(), /02 MELDUNGEN/);
    assert.equal(await page.locator('.case-input article:visible').count(), 2);
    await page.locator('#case-variant').selectOption('reviewer');
    await page.locator('#case-run').click();
    assert.match(await page.locator('#case-output').innerText(), /HOLD/);
    assert.match(await page.locator('#case-human-field').innerText(), /HOLD/);
    assert.equal(await page.locator('#case-step-human').getAttribute('data-state'), 'hold');
    await page.locator('#case-variant').selectOption('inconsistent');
    await page.locator('#case-run').click();
    assert.match(await page.locator('#case-output').innerText(), /Weitergabe widerspricht der Ursprungskennung/);
    assert.match(await page.locator('#case-origin-field').innerText(), /widersprechen/);
    await page.locator('#case-variant').selectOption('copy-change');
    await page.locator('#case-run').click();
    assert.match(await page.locator('#case-output').innerText(), /Weitergabe ändert die Aussage ihrer Vorstufe/);
    assert.match(await page.locator('#case-human-field').innerText(), /HOLD/);
    assert.equal(await page.locator('#case-step-origin').getAttribute('data-state'), 'stop');
    await page.locator('#case-variant').selectOption('late');
    await page.locator('#case-run').click();
    assert.match(await page.locator('#case-time-field').innerText(), /09:00 beobachtet, 10:04 eingetroffen/);
    assert.match(await page.locator('#case-origin-field').innerText(), /1 unabhängiger Ursprung mit aktueller Beobachtungszeit/);
    assert.match(await page.locator('#case-open-field').innerText(), /unbekannt/);
    await page.locator('#case-variant').selectOption('root-undated');
    await page.locator('#case-run').click();
    assert.match(await page.locator('#case-time-field').innerText(), /A: Ereigniszeit fehlt; B nur Kopie/);
    assert.match(await page.locator('#case-origin-field').innerText(), /0 unabhängige Ursprünge mit aktueller Beobachtungszeit/);
    assert.match(await page.locator('#case-step-time').innerText(), /A ohne Ereigniszeit/);
    if (width === 375) await page.locator('.case-grid').screenshot({path:'previews/c-drohne-undated-origin-375-20261019.png'});
    assert.equal(await page.locator('#correction-state').getAttribute('data-state'), 'HOLD');
    assert.equal(await page.locator('#correction-approve').isDisabled(), true);
    await page.locator('#correction-reject').click();
    assert.equal(await page.locator('#correction-state').getAttribute('data-state'), 'HUMAN_REJECTED_RECORDED');
    assert.match(await page.locator('#correction-receipt').textContent(), /"rawFramePersisted": false/);
    await page.locator('#correction-reset').click();
    await page.locator('#correction-correct').click();
    assert.equal(await page.locator('#correction-state').getAttribute('data-state'), 'HUMAN_CORRECTED_RECORDED');
    await page.locator('#correction-fixture').selectOption('flower-description');
    await page.locator('#correction-approve').click();
    assert.equal(await page.locator('#correction-state').getAttribute('data-state'), 'HUMAN_APPROVED_RECORD_ONLY');
    await page.locator('#correction-fixture').selectOption('cropped-ambiguous-shape');
    await page.locator('#correction-correct').click();
    assert.equal(await page.locator('#correction-state').innerText(), 'Mehrdeutigkeit festgehalten');
    assert.match(await page.locator('#correction-result').innerText(), /Beide Deutungen bleiben offen/);
    const widthState = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
    assert.ok(widthState.scroll <= widthState.client + 1, `${width}: horizontal overflow ${JSON.stringify(widthState)}`);
    await page.goto(`${base}audit-72.html`, { waitUntil: 'load' });
    assert.equal(await page.locator('.audit-card').count(), 72);
    if (width === 375 || width === 1440) await page.screenshot({ path: `previews/c-drohne-audit72-${width}-20261019.png` });
    await page.locator('[data-filter="OFFEN"]').click();
    assert.match(await page.locator('#audit-count').innerText(), /15 von 72/);
    await page.locator('.audit-jump a[href="#gruppe-1"]').click();
    assert.match(await page.locator('#audit-count').innerText(), /72 von 72/);
    await page.locator('#audit-search').fill('Kinderwagen');
    assert.ok((await page.locator('.audit-card:visible').count()) >= 1);
    const auditWidth = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
    assert.ok(auditWidth.scroll <= auditWidth.client + 1, `${width}: audit overflow ${JSON.stringify(auditWidth)}`);
    const fixture = await page.request.get(`${base}case-fixtures.json`);
    assert.equal(fixture.status(), 200);
    assert.equal((await fixture.json()).variants.length, 9);
    const measurement = await page.request.get(`${base}measurement-results.json`);
    assert.equal(measurement.status(), 200);
    assert.equal((await measurement.json()).metrics.syntheticCases, 14);
    const rights = await page.request.get(`${base}rechte.html`);
    assert.equal(rights.status(), 200);
    await page.goto(`${base}rechte.html`, { waitUntil: 'load' });
    const rightsWidth = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
    assert.ok(rightsWidth.scroll <= rightsWidth.client + 1, `${width}: rights overflow ${JSON.stringify(rightsWidth)}`);
    await page.goto(`${base}leseraum.html`, { waitUntil: 'load' });
    assert.equal(await page.locator('.reading-variants div').count(), 9);
    assert.equal(await page.locator('.reading-items article').count(), 4);
    const readingWidth = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
    assert.ok(readingWidth.scroll <= readingWidth.client + 1, `${width}: reading overflow ${JSON.stringify(readingWidth)}`);
    await page.close();
    console.log(`PASS ${width}px: main, route focus, nine case variants, correction states, 72 cards, reflow`);
  }
  const noJs = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 375, height: 760 } });
  await noJs.goto(base, { waitUntil: 'load' });
  assert.ok(await noJs.locator('.static-alternative:visible').count());
  assert.ok(await noJs.locator('#korrektur .static-alternative:visible').count());
  assert.ok(await noJs.locator('a[href="audit-72.html"]:visible').count());
  await noJs.goto(`${base}audit-72.html`, { waitUntil: 'load' });
  assert.equal(await noJs.locator('.audit-card').count(), 72);
  await noJs.goto(`${base}leseraum.html`, { waitUntil: 'load' });
  assert.equal(await noJs.locator('.reading-variants div').count(), 9);
  console.log('PASS no JavaScript: static object/fall text, all 72 answers, full reading path');
  assert.deepEqual(failures, []);
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
